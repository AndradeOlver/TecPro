    private void btnBuscarCodigoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarCodigoActionPerformed
  // 1. Recolección
        String codigoBuscado = textBusquedaCodigo.getText().trim();
        
        // 2. Validación proactiva para evitar letras sin usar try-catch
        if (!codigoBuscado.matches("^[0-9]+$")) {
             javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese únicamente números para la búsqueda.");
             return; // Detiene la ejecución
        }
    
        // 3. Búsqueda
        Proveedor proveedorEncontrado = gestor.buscarProveedorPorRuc(codigoBuscado);
    
        // 4. Renderizado visual
        if (proveedorEncontrado == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "El RUC no está registrado en el sistema.");
        } else {
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblClientes.getModel();
            modelo.setRowCount(0); 
            
            // Orden de las columnas corregido
            modelo.addRow(new Object[]{
                proveedorEncontrado.getRuc(),
                proveedorEncontrado.getRazonSocial(),
                proveedorEncontrado.getDireccion(),
                proveedorEncontrado.getContacto(),
                proveedorEncontrado.getNumeroContacto(), 
                proveedorEncontrado.getCorreoContacto()
            });
            
            btnQuitarFiltro.setVisible(true);
            textBusquedaCodigo.setText("");
        }

    }//GEN-LAST:event_btnBuscarCodigoActionPerformed

