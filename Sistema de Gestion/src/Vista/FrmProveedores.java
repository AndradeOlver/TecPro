    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String codigo = textCodigo.getText().trim();
            
            // NUEVA LÓGICA PROACTIVA: Validación del RUC (solo 11 números)
            if (!codigo.matches("^[0-9]{11}$")) {
                JOptionPane.showMessageDialog(this, "Error: El RUC debe contener exactamente 11 números.", "Error de Formato", JOptionPane.ERROR_MESSAGE);  
                return; // Aborta la operación aquí mismo
            }

            String nombre = textNombre.getText();
            String direccion = textDireccion.getText();
            String contacto = textContacto.getText();
            String numero = textNumero.getText();
            String correo = textCorreo.getText();
            
            // B. Instanciación (Orden corregido: RUC, Nombre, Direccion, Contacto, Numero, Correo)
            Proveedor nuevoProveedor = new Proveedor(codigo, nombre, direccion, contacto, numero, correo);
            
            // C. Delegación
            gestor.registrarProveedor(nuevoProveedor);
            
            // D. Éxito (Textos corregidos)
            JOptionPane.showMessageDialog(this, "Proveedor registrado con éxito.");
            limpiarCajas();
            actualizarTabla();
        
        } catch (IllegalArgumentException ex) {
            // Intercepción de las reglas de negocio
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error de Validación", JOptionPane.WARNING_MESSAGE);
        }
        
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarPorNombreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarPorNombreActionPerformed
        String textoBusqueda = textBusquedaNombre.getText();
    
        if (textoBusqueda.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe escribir una razón social para buscar.");
            return; 
        }
    
        List<Proveedor> listaResultados = gestor.buscarProveedorPorNombre(textoBusqueda);
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblClientes.getModel();
    
        if (listaResultados.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontraron proveedores con ese nombre.");
            modelo.setRowCount(0); 
        } else {
            modelo.setRowCount(0); 
            
            for (Proveedor p : listaResultados) {
                // Orden de columnas estrictamente alineado a tu diseño:
                // RUC, Nombre, Dirección, Contacto, Numero, Correo
                modelo.addRow(new Object[]{
                    p.getRuc(),
                    p.getRazonSocial(),
                    p.getDireccion(),
                    p.getContacto(),
                    p.getNumeroContacto(),
                    p.getCorreoContacto()
                });
             }
             
            btnQuitarFiltro.setVisible(true);
            textBusquedaNombre.setText("");
        }
     
        
    }//GEN-LAST:event_btnBuscarPorNombreActionPerformed

