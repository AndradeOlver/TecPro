    private void tblProveedoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProveedoresMouseClicked
        // TODO add your handling code here:
        if (evt.getClickCount() == 2) { // ¿Fueron dos clics seguidos?
            int fila = tblProveedores.getSelectedRow();
            
            if (fila != -1) {
                // Extraemos el RUC de la primera columna (columna 0)
                String ruc = tblProveedores.getValueAt(fila, 0).toString();
                
                // Usamos el gestor de contactos para encontrar al objeto real
                this.proveedorSeleccionado = gestor.buscarProveedorPorRuc(ruc);
                
                // Cerramos la ventana para devolver la información
                this.dispose(); 
            }
        }
    }//GEN-LAST:event_tblProveedoresMouseClicked
    // Método estético auxiliar
    private void ajustarAnchoColumnas() {
        javax.swing.table.TableColumnModel modeloColumna = tblProveedores.getColumnModel();
        for (int i = 0; i < modeloColumna.getColumnCount(); i++) {
            int anchoCalculado = 50; 
            javax.swing.table.TableColumn columna = modeloColumna.getColumn(i);
            javax.swing.table.TableCellRenderer rendererCabecera = columna.getHeaderRenderer();
            if (rendererCabecera == null) rendererCabecera = tblProveedores.getTableHeader().getDefaultRenderer();
            java.awt.Component compCabecera = rendererCabecera.getTableCellRendererComponent(tblProveedores, columna.getHeaderValue(), false, false, 0, i);
            anchoCalculado = Math.max(anchoCalculado, compCabecera.getPreferredSize().width);
            for (int j = 0; j < tblProveedores.getRowCount(); j++) {
                javax.swing.table.TableCellRenderer rendererCelda = tblProveedores.getCellRenderer(j, i);
                java.awt.Component compCelda = rendererCelda.getTableCellRendererComponent(tblProveedores, tblProveedores.getValueAt(j, i), false, false, j, i);
                anchoCalculado = Math.max(anchoCalculado, compCelda.getPreferredSize().width);
            }
            columna.setPreferredWidth(anchoCalculado + 10);
        }
    }
