    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String textoBusqueda = txtBuscarProveedor.getText().trim();
        List<Proveedor> listaResultados;
        
        // Decidimos qué lista mostrar según la caja de texto
        if (textoBusqueda.isEmpty()) {
            listaResultados = gestor.obtenerTodosLosProveedores();
        } else {
            listaResultados = gestor.buscarProveedorPorNombre(textoBusqueda);
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tblProveedores.getModel();
        modelo.setRowCount(0); // Limpiamos
        
        // Llenamos la tabla
        for (Proveedor p : listaResultados) {
            modelo.addRow(new Object[]{
                p.getRuc(), 
                p.getRazonSocial(), 
                p.getDireccion(), 
                p.getContacto(), 
                p.getNumeroContacto(), 
                p.getCorreoContacto()
            });
        }
        ajustarAnchoColumnas();
    }//GEN-LAST:event_btnBuscarActionPerformed

