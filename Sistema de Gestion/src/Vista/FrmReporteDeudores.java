    private void btnCobrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCobrarActionPerformed
        int fila = tblDeudores.getSelectedRow();
        if (fila != -1) {
            try {
                // Sacamos el ID del pedido de la primera columna
                int codigo = Integer.parseInt(tblDeudores.getValueAt(fila, 0).toString());
                Pedido pedidoDeudor = gestorVentas.obtenerDetallesDePedido(codigo);

                if (pedidoDeudor != null) {
                    // Reutilizamos tu ventana de caja existente
                    jdialProcesarVenta caja = new jdialProcesarVenta(this, true);
                    caja.prepararCobro(pedidoDeudor, gestorVentas);
                    caja.setLocationRelativeTo(this);
                    
                    // Se pausa aquí hasta cobrar
                    caja.setVisible(true);
                    
                    // Al cerrar la caja, la tabla se actualiza sola (desaparece si pagó todo)
                    cargarDeudores();
                }
            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un deudor de la lista primero.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
        
    }//GEN-LAST:event_btnCobrarActionPerformed

