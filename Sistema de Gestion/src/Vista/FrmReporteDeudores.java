    // Método que filtra y ordena a los que deben dinero
    private void cargarDeudores() {
        DefaultTableModel modelo = (DefaultTableModel) tblDeudores.getModel();
        modelo.setRowCount(0);

        // Pedimos todos los pedidos, filtramos solo los que deben > 0 y los ordenamos por fecha
        List<Pedido> deudores = gestorVentas.obtenerHistorialPedidos().stream()
                .filter(p -> p.getDeudaPendiente() > 0)
                .sorted((p1, p2) -> p1.getFechaLimitePago().compareTo(p2.getFechaLimitePago()))
                .collect(Collectors.toList());

        for (Pedido p : deudores) {
             modelo.addRow(new Object[]{
                p.getCodigo(),
                p.getCliente().getNombre(),
                p.getCliente().getNumeroContacto(),
                p.getFechaEmision(),             // <- AGREGADO (Para la columna "Fecha")
                p.getFechaLimitePago(),          // (Para la columna "Límite")
                String.format("S/ %.2f", p.getDeudaPendiente()) // (Para la columna "Deuda")
            });
        }
    }
